#!/usr/bin/env python3
"""Embed waves/*.wav (single cycle, 2048 samples, 16 bit mono) into src/WaveData.h.
Run from the repo root: python3 tools/embed_waves.py"""
import os, wave, struct
first = ["sine", "triangle", "saw", "bright_saw", "square", "pulse25", "pulse10"]
names = sorted(f[:-4] for f in os.listdir("waves") if f.endswith(".wav"))
names = [n for n in first if n in names] + [n for n in names if n not in first]
out = ["// Generated by tools/embed_waves.py. Do not edit by hand.", "#pragma once", "namespace whisker {",
       f"constexpr int kNumWaves = {len(names)};", "constexpr int kWaveLen = 2048;",
       "inline const char* const kWaveNames[kNumWaves] = {" + ", ".join(f'"{n}"' for n in names) + "};",
       "inline const short kWaveData[kNumWaves][kWaveLen] = {"]
for n in names:
    w = wave.open(f"waves/{n}.wav")
    assert w.getnframes() == 2048 and w.getsampwidth() == 2 and w.getnchannels() == 1, n
    d = struct.unpack("<2048h", w.readframes(2048))
    out.append("{" + ",".join(map(str, d)) + "},")
out += ["};", "}"]
open("src/WaveData.h", "w").write("\n".join(out) + "\n")
print(len(names), "waves embedded")
