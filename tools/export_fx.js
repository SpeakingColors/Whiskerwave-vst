// Exports the FX registry (types, parameters, lists, tips) to src/FxTable.h.
// Usage: node tools/export_fx.js /path/to/ww-dsp.js
const fs = require('fs');
const G = {};
new Function('G', fs.readFileSync(process.argv[2], 'utf8') + ';WWMAKE(G);')(G);
const types = Object.keys(G.FXDEF);
const esc = s => JSON.stringify(String(s || ''));
const fl = v => { let t = String(+v); if (/e/i.test(t)) t = (+v).toFixed(9); if (!/[.]/.test(t)) t += '.0'; return t + 'f'; };
let maxP = 0; for (const t of types) maxP = Math.max(maxP, G.FXDEF[t].order.length);
let h = '// Generated by tools/export_fx.js. Do not edit by hand.\n#pragma once\n#include "ParamTable.h"\nnamespace whisker {\n';
h += `constexpr int kNumFxTypes = ${types.length}; constexpr int kMaxFxParams = ${maxP + 2};\n`;
h += 'enum FxType : int {\n' + types.map((t, i) => `  FX_${t} = ${i},`).join('\n') + '\n};\n';
h += 'struct FxParamSpec { const char* key; const char* label; float mn, mx, def; PK kind; const char* unit; const char* tip; const char* const* items; int nItems; };\n';
h += 'struct FxSpec { const char* type; const char* name; const char* cat; const char* tip; int np; const FxParamSpec* ps; int mixIdx; bool special; };\n';
for (const t of types) {
  const d = G.FXDEF[t];
  for (const s of d.order) if (s.list) h += `inline const char* const kFxList_${t}_${s.key}[] = {${s.list.map(esc).join(', ')}};\n`;
  h += `inline const FxParamSpec kFxPs_${t}[] = {\n`;
  for (const s of d.order) {
    const kind = s.k === 'exp' ? 'Exp' : s.k === 'int' ? 'Int' : s.k === 'list' ? 'List' : 'Lin';
    h += `  {${esc(s.key)}, ${esc(s.l)}, ${fl(s.min)}, ${fl(s.max)}, ${fl(s.d)}, PK::${kind}, ${esc(s.u)}, ${esc(s.tip)}, ${s.list ? `kFxList_${t}_${s.key}, ${s.list.length}` : 'nullptr, 0'}},\n`;
  }
  h += '};\n';
}
h += 'inline const FxSpec kFx[kNumFxTypes] = {\n';
for (const t of types) {
  const d = G.FXDEF[t]; const mi = d.order.findIndex(s => s.key === 'mix');
  h += `  {${esc(t)}, ${esc(d.name)}, ${esc(d.cat)}, ${esc(d.tip)}, ${d.order.length}, kFxPs_${t}, ${mi}, ${d.special ? 'true' : 'false'}},\n`;
}
h += '};\n';
h += 'namespace fxp {\n';
for (const t of types) h += `namespace ${t} { enum { ${G.FXDEF[t].order.map((s, i) => `p_${s.key} = ${i}`).join(', ')} }; }\n`;
h += '}\n';
// category order and per type lookup by name
h += `inline const char* const kFxCats[] = {${G.FXCATS.map(esc).join(', ')}}; constexpr int kNumFxCats = ${G.FXCATS.length};\n`;
h += '}\n';
fs.writeFileSync('src/FxTable.h', h);
console.log(types.length, 'fx types, max params', maxP);
// plain data for the manual
fs.mkdirSync('data', { recursive: true });
fs.writeFileSync('data/fx.json', JSON.stringify(types.map(t => { const d = G.FXDEF[t]; return { type: t, name: d.name, cat: d.cat, tip: d.tip, ps: d.order.map(s => ({ key: s.key, l: s.l, min: s.min, max: s.max, d: s.d, k: s.k, u: s.u, tip: s.tip, list: s.list || null })) }; })));
fs.writeFileSync('data/params.json', JSON.stringify(Object.keys(G.PR).map(k => { const p = G.PR[k]; return { key: k, l: p.l, min: p.min, max: p.max, d: p.d, k: p.k, u: p.u || '', tip: p.tip || '', list: typeof p.list === 'string' ? G.LISTS[p.list] : (p.list || null) }; })));
