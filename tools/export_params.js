// Exports every mockup parameter (729) and all list texts to src/ParamTable.h.
// Usage: node tools/export_params.js /path/to/ww-dsp.js
const fs = require('fs');
const G = {};
new Function('G', fs.readFileSync(process.argv[2], 'utf8') + ';WWMAKE(G);')(G);
const PR = G.PR, keys = Object.keys(PR);
const id = k => k.replace(/\./g, '_');
const esc = s => JSON.stringify(String(s || ''));
const fl = v => { let t = String(+v); if (/e/i.test(t)) t = (+v).toFixed(9); if (!/[.]/.test(t)) t += '.0'; return t + 'f'; };
let h = '// Generated by tools/export_params.js. Do not edit by hand.\n#pragma once\n#include <cstdint>\nnamespace whisker {\n';
h += `constexpr int kNumParams = ${keys.length};\n`;
h += 'enum PIdx : int {\n' + keys.map((k, i) => `  P_${id(k)} = ${i},`).join('\n') + '\n};\n';
h += 'enum class PK : uint8_t { Lin, Exp, Int, List };\n';
h += 'struct ParamSpec { const char* key; const char* id; const char* label; float mn, mx, def; PK kind; bool perVoice; const char* unit; const char* list; const char* tip; };\n';
h += 'inline const ParamSpec kParams[kNumParams] = {\n';
for (const k of keys) {
  const p = PR[k];
  const kind = p.k === 'exp' ? 'Exp' : p.k === 'int' ? 'Int' : p.k === 'list' ? 'List' : 'Lin';
  h += `  {${esc(k)}, ${esc(id(k))}, ${esc(p.l)}, ${fl(p.min)}, ${fl(p.max)}, ${fl(p.d)}, PK::${kind}, ${p.vo ? 'true' : 'false'}, ${esc(p.u)}, ${esc(typeof p.list === 'string' ? p.list : '')}, ${esc(p.tip)}},\n`;
}
h += '};\n';
// lists
const lk = Object.keys(G.LISTS);
h += 'struct ListSpec { const char* name; int n; const char* const* items; };\n';
for (const l of lk) h += `inline const char* const kList_${l}[] = {${G.LISTS[l].map(esc).join(', ')}};\n`;
h += 'inline const ListSpec kLists[] = {\n' + lk.map(l => `  {${esc(l)}, ${G.LISTS[l].length}, kList_${l}},`).join('\n') + '\n};\n';
h += `constexpr int kNumLists = ${lk.length};\n}\n`;
fs.writeFileSync('src/ParamTable.h', h);
console.log(keys.length, 'params,', lk.length, 'lists');
