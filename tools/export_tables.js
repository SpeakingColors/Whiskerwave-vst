// Exports the 41 mockup wavetables (32 frames x 2048 samples, int16) to data/ww_tables.bin and src/TableNames.h.
// Usage: node tools/export_tables.js /path/to/ww-dsp.js
const fs = require('fs');
const G = {};
new Function('G', fs.readFileSync(process.argv[2], 'utf8') + ';WWMAKE(G);')(G);
const names = G.recipeNames();
const NF = 32, N = 2048;
const buf = Buffer.alloc(names.length * NF * N * 2);
let o = 0;
for (const r of names) {
  const wt = G.makeTable(r.name, NF);
  for (let f = 0; f < NF; f++) for (let i = 0; i < N; i++) {
    const v = Math.max(-1, Math.min(1, wt.src[f][i]));
    buf.writeInt16LE(Math.round(v * 32767), o); o += 2;
  }
}
fs.writeFileSync('data/ww_tables.bin', buf);
let h = '// Generated by tools/export_tables.js. Do not edit by hand.\n#pragma once\nnamespace whisker {\n';
h += `constexpr int kNumTables = ${names.length};\nconstexpr int kTableFrames = ${NF};\nconstexpr int kTableLen = ${N};\n`;
h += 'inline const char* const kTableNames[kNumTables] = {' + names.map(r => JSON.stringify(r.name)).join(', ') + '};\n';
h += 'inline const char* const kTableCats[kNumTables] = {' + names.map(r => JSON.stringify(r.cat)).join(', ') + '};\n}\n';
fs.writeFileSync('src/TableNames.h', h);
console.log(names.length, 'tables,', buf.length, 'bytes');
